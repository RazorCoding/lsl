#!/usr/bin/env python3
"""Turn Anime4K's Restore CNN GLSL into a C table of weights.

usage: anime4k_weights.py <Anime4K_Restore_CNN_S.glsl> <out.h>

lsl runs bloc97's Anime4K v4 Restore CNN (MIT) as compute dispatches over
storage buffers rather than as an mpv hook, so the weights have to leave the
GLSL.  They are not retyped by hand: this reads the vendored .glsl, checks that
it has the shape the shader and the CPU reference assume, and writes the header
both of them include.  The .glsl stays the single source of truth and CMake
re-runs this whenever it changes.

The network is four 3x3 convolutions at one resolution:

    layer 0:  in = the base image (RGB)                 -> 4 channels
    layer 1:  in = layer 0, split into relu(x)/relu(-x) -> 4 channels
    layer 2:  in = layer 1, split                       -> 4 channels
    layer 3:  in = layer 2, split, plus the base image  -> RGB

Every layer visits its 3x3 neighbourhood in the same order, so the offsets are
a constant in the generated header rather than data.  That is checked here.
"""
import re
import sys
from pathlib import Path

TAP_ORDER = [(-1, -1), (-1, 0), (-1, 1),
             (0, -1), (0, 0), (0, 1),
             (1, -1), (1, 0), (1, 1)]


def parse(text):
    layers = []
    # Split on the //!DESC markers, because a layer's #define go_0/go_1 lines
    # sit above its hook() and would otherwise land in the previous layer.
    for block in re.split(r"//!DESC", text)[1:]:
        split = "#define go_1" in block
        add_base = "MAIN_tex(MAIN_pos)" in block
        taps = []
        for m in re.finditer(
            r"mat4\(([^)]*)\)\s*\*\s*go_(\d)\(\s*(-?[\d.]+),\s*(-?[\d.]+)\s*\)",
            block,
        ):
            vals = [float(v) for v in m.group(1).split(",")]
            taps.append((int(float(m.group(3))), int(float(m.group(4))),
                         int(m.group(2)), vals))
        bm = re.search(r"vec4\(([^)]*)\);\s*\n\s*return", block)
        bias = [float(v) for v in bm.group(1).split(",")] if bm else None
        layers.append({"split": split, "add_base": add_base,
                       "taps": taps, "bias": bias})
    return layers


def validate(layers):
    if len(layers) != 4:
        sys.exit("expected 4 layers, found %d" % len(layers))
    for n, layer in enumerate(layers):
        want = 18 if layer["split"] else 9
        if len(layer["taps"]) != want:
            sys.exit("layer %d: expected %d taps, found %d"
                     % (n, want, len(layer["taps"])))
        if not layer["bias"] or len(layer["bias"]) != 4:
            sys.exit("layer %d: missing or malformed bias" % n)
        for t, (x, y, go, vals) in enumerate(layer["taps"]):
            if len(vals) != 16:
                sys.exit("layer %d tap %d: %d weights, want 16"
                         % (n, t, len(vals)))
            expect = TAP_ORDER[t % 9]
            if (x, y) != expect:
                sys.exit("layer %d tap %d: offset %s != %s"
                         % (n, t, (x, y), expect))
            if layer["split"] and go != (0 if t < 9 else 1):
                sys.exit("layer %d tap %d: go_%d in the wrong half"
                         % (n, t, go))


def fmt(v):
    s = "%.9g" % v
    # A GLSL/C++ float literal needs a point or an exponent: "0f" is not one.
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s + "f"


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    layers = parse(src.read_text())
    validate(layers)

    weights = []
    descs = []
    for layer in layers:
        woff = len(weights)
        for _x, _y, _go, vals in layer["taps"]:
            weights.extend(vals)
        boff = len(weights)
        weights.extend(layer["bias"])
        descs.append((1 if layer["split"] else 0,
                      1 if layer["add_base"] else 0, woff, boff))

    lines = [
        "/* Generated by tools/anime4k_weights.py -- do not edit by hand.",
        " *",
        " * Weights for bloc97's Anime4K v4 Restore CNN (S), MIT licensed.  The",
        " * source they are derived from is",
        " * third_party/anime4k/Anime4K_Restore_CNN_S.glsl; src/cnn_ref.cpp shows",
        " * how the CPU reference uses them and shaders/cnn.comp the GPU side.",
        " */",
        "#pragma once",
        "",
        "/* The 3x3 neighbourhood order every layer walks. */",
        "static const int lsl_anime4k_offsets[9][2] = {",
    ]
    for x, y in TAP_ORDER:
        lines.append("    {%d, %d}," % (x, y))
    lines += [
        "};",
        "",
        "/* Every layer walks %d taps; a split layer stores all of its go_0" % len(TAP_ORDER),
        " * matrices first and its go_1 matrices after them. */",
        "#define LSL_ANIME4K_TAPS %d" % len(TAP_ORDER),
        "#define LSL_ANIME4K_GO1_OFFSET (LSL_ANIME4K_TAPS * 16)",
        "",
        "/* The bits in shaders/cnn.comp's push-constant `flags`, plus how a caller",
        " * sequences the four layers: scratch A is written by layer 0, layer 1",
        " * reads A and writes B, layer 2 reads B and writes A, and layer 3 reads",
        " * A, adds the base image and writes the packed result.  The shader",
        " * spells these values out inline because it cannot include this file,",
        " * so they are stated here once for the C side to share. */",
        "#define LSL_CNN_SPLIT       (1u << 0)",
        "#define LSL_CNN_ADD_BASE    (1u << 1)",
        "#define LSL_CNN_READ_BASE   (1u << 2)",
        "#define LSL_CNN_WRITE_IMAGE (1u << 3)",
        "#define LSL_CNN_SRC_B       (1u << 4)",
        "#define LSL_CNN_DST_B       (1u << 5)",
        "",
        "typedef struct {",
        "    int split;     /* 1: relu(x)/relu(-x) per tap; 0: one matrix per tap */",
        "    int add_base;  /* 1: add the base image back at the end */",
        "    int woff;      /* first matrix in lsl_anime4k_weights */",
        "    int boff;      /* this layer's bias in lsl_anime4k_weights */",
        "} LslAnime4kLayer;",
        "",
        "#define LSL_ANIME4K_LAYERS %d" % len(layers),
        "",
        "static const LslAnime4kLayer "
        "lsl_anime4k_layers[LSL_ANIME4K_LAYERS] = {",
    ]
    for split, add_base, woff, boff in descs:
        lines.append("    {%d, %d, %d, %d}," % (split, add_base, woff, boff))
    lines += [
        "};",
        "",
        "#define LSL_ANIME4K_WEIGHT_COUNT %d" % len(weights),
        "",
        "static const float "
        "lsl_anime4k_weights[LSL_ANIME4K_WEIGHT_COUNT] = {",
    ]
    for i in range(0, len(weights), 4):
        chunk = ", ".join(fmt(v) for v in weights[i:i + 4])
        lines.append("    %s," % chunk)
    lines += ["};", ""]

    src_line = "\n".join(lines) + "\n"
    out.write_text(src_line)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
